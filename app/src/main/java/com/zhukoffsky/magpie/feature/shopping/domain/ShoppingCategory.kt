package com.zhukoffsky.magpie.feature.shopping.domain

/**
 * Отдел магазина.
 *
 * **Перечень закрытый, а не свободная строка от модели.** Спрошенная без
 * ограничений, она вернёт на одно и то же «молочка», «Молочные продукты» и
 * «Dairy» — группы раскрошатся, и список станет хуже плоского. Поэтому
 * категории заданы здесь, а промпт получает ровно этот список.
 *
 * **Набор — отделы супермаркета, а не выдуманная классификация.** С
 * 4 ноября 2026 их двадцать три. Сверено с каталогами четырёх стран:
 * Green (Беларусь), «ВкусВилл» (Россия), Mercadona (Испания) и типовые
 * проходы американского супермаркета. Где все четыре делят одинаково, так
 * делим и мы: мясо, рыба и колбасы — три прилавка; бакалея — четыре ряда
 * (крупы, консервы, масла и соусы, завтраки); сладости отдельно от снеков.
 * «Здоровье» есть в трёх из четырёх.
 *
 * **[GROCERY] — это «Крупы, макароны, мука».** Имя осталось от времён, когда
 * бакалея была одним отделом: позиции в базе хранят его строкой, и
 * переименование выбросило бы их в «Прочее».
 *
 * **Порядок объявления — это порядок обхода магазина**, в нём и рисуется
 * список: свежее в начале, заморозка ближе к кассе, непродовольственное
 * последним. [OTHER] намеренно последний: туда попадает всё, чего не узнали ни
 * модель, ни словарь ([ShoppingCategoryDictionary]).
 */
enum class ShoppingCategory {
    PRODUCE,
    BAKERY,
    READY_MEALS,
    DAIRY,
    CHEESE,
    MEAT,
    FISH,
    DELI,
    GROCERY,
    CANNED,
    CONDIMENTS,
    BREAKFAST,
    SWEETS,
    SNACKS,
    TEA_COFFEE,
    DRINKS,
    ALCOHOL,
    FROZEN,
    HOUSEHOLD,
    HYGIENE,
    HEALTH,
    KIDS,
    PETS,
    OTHER,
    ;

    companion object {
        /**
         * Неизвестное название — это [OTHER], а не ошибка.
         *
         * Модель обещает отвечать одним из перечисленных значений, но обещание
         * — не гарантия; в базе к тому же лежат позиции, записанные до
         * появления категорий.
         */
        fun fromName(value: String?): ShoppingCategory =
            entries.firstOrNull { it.name.equals(value?.trim(), ignoreCase = true) } ?: OTHER
    }
}

/**
 * Разобранная позиция списка.
 *
 * Категория необязательна: её называет модель или словарь, а незнакомую
 * позицию оба оставляют без неё.
 */
data class ParsedShoppingItem(
    val title: String,
    val category: ShoppingCategory? = null,
)
