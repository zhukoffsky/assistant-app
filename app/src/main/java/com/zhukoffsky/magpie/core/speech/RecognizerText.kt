package com.zhukoffsky.magpie.core.speech

/**
 * Убрать запятые, которые расставил распознаватель на телефоне.
 *
 * Он ставит их по интонации, а не по смыслу: 4 ноября из двенадцати границ
 * в живой диктовке три оказались не там — «яйца, куриные», «яблоки,
 * зелёные бананы», «вино, красное сухое средство для мытья посуды». Правила
 * режут по запятой не раздумывая, поэтому каждая такая запятая — испорченная
 * позиция. Без них правила видят фразу целиком и на той же диктовке режут
 * все двенадцать верно.
 *
 * Точки остаются: ими распознаватель закрывает сегмент на паузе, а пауза —
 * граница надёжная. Запятая внутри числа («2,5%») тоже остаётся.
 * Запятые Whisper не трогаем: его текст уходит модели, а она в них не путается.
 */
fun dropRecognizerCommas(text: String): String = text.replace(COMMA, "")

private val COMMA = Regex(""",(?=\s|$)""")
