package com.zhukoffsky.magpie.core.speech

/**
 * Расшифровка записанного звука в текст.
 *
 * Интерфейс отделяет провайдера от всего остального ровно по той же
 * причине, что и `PhraseParser` у напоминаний: сервис выбран по
 * доступности из России, а не навсегда, и менять его придётся.
 *
 * Здесь принципиально **вся запись целиком**, а не поток. Потоковое
 * распознавание — это и есть `SpeechRecognizer`, чужая сессия, которая
 * заканчивается когда хочет; от неё ушли специально. Микрофоном теперь
 * владеет приложение, а запись заканчивает только человек.
 */
fun interface SpeechTranscriber {

    /**
     * @param audio содержимое файла OggOpus целиком.
     * @param languageTag язык записи, например `ru-RU`.
     * @return распознанный текст или `null`, если расшифровать не удалось.
     *         Пустая строка — это тоже неудача: значит, ничего не расслышали.
     */
    suspend fun transcribe(audio: ByteArray, languageTag: String): String?
}
