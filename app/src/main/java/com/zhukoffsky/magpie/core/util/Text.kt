package com.zhukoffsky.magpie.core.util

/**
 * Пробел в том виде, в каком он приезжает из распознавания речи.
 *
 * `\s` в Java — это `[ \t\n\x0B\f\r]` и ничего больше: **неразрывный пробел
 * U+00A0 под него не подходит**. А распознаватель его ставит: 12 августа
 * «напомни<U+00A0>съездить на рынок завтра в 15:00» приехало именно так, и
 * регулярка, вычёркивающая вводное «напомни», просто не нашла после него
 * пробела. В заголовке осталось «напомни съездить на рынок» — на глаз
 * неотличимо от обычного пробела, поэтому искать пришлось перебором.
 *
 * Родня той же ловушки, что и `\b` с кириллицей: значения по умолчанию в
 * Java-регулярках рассчитаны на латиницу и ASCII.
 */
// Escape-последовательности записаны текстом намеренно: raw-строка Kotlin их
// не разворачивает, а движок регулярок понимает сам. Настоящий U+00A0 в
// исходнике был бы неотличим от обычного пробела — ровно то, на чём и
// потерялось время.
const val SPACE = """[\s\u00A0\u2007\u202F]"""

private val spaces = Regex("$SPACE+")

/** Схлопывает любые пробелы, включая неразрывные, в один обычный. */
fun String.normalizeSpaces(): String = replace(spaces, " ").trim()
